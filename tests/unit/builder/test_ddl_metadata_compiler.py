def test_create_table_from_metadata_composite_pk_fk_check_unique_defaults_and_computed() -> None:
    """Test CreateTable.from_metadata with composite PK, FK, CHECK, UNIQUE, defaults, identity, and computed columns."""
    columns: list[dict[str, Any]] = [
        {
            "column_name": "tenant_id",
            "data_type": "UUID",
            "is_nullable": "NO",
            "ordinal_position": 1,
            "primary_key_ordinal": 1,
            "primary_key_name": "pk_orders",
        },
        {
            "column_name": "id",
            "data_type": "BIGINT",
            "is_nullable": False,
            "ordinal_position": 2,
            "identity_generation": "d",
            "primary_key_ordinal": 2,
            "primary_key_name": "pk_orders",
        },
        {
            "column_name": "customer_id",
            "data_type": "UUID",
            "is_nullable": "NO",
            "ordinal_position": 3,
        },
        {
            "column_name": "order_code",
            "data_type": "VARCHAR",
            "max_length": 64,
            "is_nullable": "NO",
            "ordinal_position": 4,
            "collation": "C",
        },
        {
            "column_name": "status",
            "data_type": "VARCHAR",
            "max_length": 32,
            "is_nullable": "NO",
            "column_default": "'pending'",
            "ordinal_position": 5,
        },
        {
            "column_name": "unit_price",
            "data_type": "NUMERIC",
            "numeric_precision": 12,
            "numeric_scale": 2,
            "is_nullable": "NO",
            "ordinal_position": 6,
        },
        {
            "column_name": "quantity",
            "data_type": "INTEGER",
            "is_nullable": "NO",
            "column_default": "1",
            "ordinal_position": 7,
        },
        {
            "column_name": "line_total",
            "data_type": "NUMERIC",
            "numeric_precision": 12,
            "numeric_scale": 2,
            "is_nullable": "YES",
            "is_computed": True,
            "computed_definition": "unit_price * quantity",
            "is_persisted_computed": True,
            "ordinal_position": 8,
        },
        {
            "column_name": "created_at",
            "data_type": "TIMESTAMPTZ",
            "is_nullable": "NO",
            "column_default": "CURRENT_TIMESTAMP",
            "ordinal_position": 9,
        },
    ]
    constraints: list[dict[str, Any]] = [
        {
            "constraint_name": "pk_orders",
            "constraint_type": "PRIMARY KEY",
            "columns": ["tenant_id", "id"],
        },
        {
            "constraint_name": "uq_orders_tenant_code",
            "constraint_type": "UNIQUE",
            "columns": ["tenant_id", "order_code"],
        },
        {
            "constraint_name": "chk_orders_positive_qty",
            "constraint_type": "CHECK",
            "definition": "CHECK (quantity > 0)",
        },
        {
            "constraint_name": "fk_orders_customer",
            "constraint_type": "FOREIGN KEY",
            "columns": ["customer_id"],
            "referenced_table": "customers",
            "referenced_columns": ["id"],
            "on_delete": "CASCADE",
            "on_update": "SET NULL",
        },
    ]
    foreign_keys = [
        ForeignKeyMetadata(
            table_name="orders",
            column_name="customer_id",
            referenced_table="customers",
            referenced_column="id",
            constraint_name="fk_orders_customer",
            schema="sales",
            referenced_schema="sales",
        )
    ]

    builder = CreateTable.from_metadata(
        "orders",
        columns,
        constraints=constraints,
        foreign_keys=foreign_keys,
        schema="sales",
        if_not_exists=True,
        dialect="postgres",
    )
    sql = builder.build().sql

    assert 'CREATE TABLE IF NOT EXISTS "sales"."orders"' in sql
    assert '"id" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY' in sql
    assert '"order_code" VARCHAR(64) NOT NULL COLLATE "C"' in sql
    assert "\"status\" VARCHAR(32) NOT NULL DEFAULT 'pending'" in sql
    assert '"unit_price" DECIMAL(12, 2) NOT NULL' in sql
    assert '"quantity" INT NOT NULL DEFAULT 1' in sql
    assert '"line_total" DECIMAL(12, 2) GENERATED ALWAYS AS ("unit_price" * "quantity") STORED' in sql
    assert '"created_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP' in sql
    assert 'CONSTRAINT "pk_orders" PRIMARY KEY ("tenant_id", "id")' in sql
    assert 'CONSTRAINT "uq_orders_tenant_code" UNIQUE ("tenant_id", "order_code")' in sql
    assert 'CONSTRAINT "chk_orders_positive_qty" CHECK ("quantity" > 0)' in sql
    assert (
        'CONSTRAINT "fk_orders_customer" FOREIGN KEY ("customer_id") '
        'REFERENCES "customers"("id") ON DELETE CASCADE ON UPDATE SET NULL'
    ) in sql
    assert sql.count("fk_orders_customer") == 1
    assert sql.count("pk_orders") == 1


def test_create_table_from_metadata_struct_objects_and_mssql_types() -> None:
    """Test CreateTable.from_metadata with ColumnDetails, ConstraintMetadata, and MSSQL type rules."""
    columns = [
        ColumnDetails(
            ObjectIdentity(name="id", object_type="column", schema="dbo", dialect="mssql"),
            attributes={
                "data_type": "int",
                "max_length": 4,
                "numeric_precision": 10,
                "numeric_scale": 0,
                "is_nullable": False,
                "is_identity": True,
                "identity_seed": 1,
                "identity_increment": 1,
                "primary_key_name": "pk_accounts",
                "primary_key_ordinal": 1,
                "ordinal_position": 1,
            },
        ),
        ColumnDetails(
            ObjectIdentity(name="display_name", object_type="column", schema="dbo", dialect="mssql"),
            attributes={
                "data_type": "nvarchar",
                "max_length": 200,
                "is_nullable": False,
                "column_default": "('unknown')",
                "ordinal_position": 2,
            },
        ),
        ColumnDetails(
            ObjectIdentity(name="payload", object_type="column", schema="dbo", dialect="mssql"),
            attributes={
                "data_type": "nvarchar",
                "max_length": -1,
                "is_nullable": True,
                "ordinal_position": 3,
            },
        ),
        ColumnDetails(
            ObjectIdentity(name="event_time", object_type="column", schema="dbo", dialect="mssql"),
            attributes={
                "data_type": "datetime2",
                "numeric_scale": 3,
                "is_nullable": False,
                "ordinal_position": 4,
            },
        ),
    ]
    constraints = [
        ConstraintMetadata(
            ObjectIdentity(name="chk_display_name", object_type="constraint", schema="dbo", dialect="mssql"),
            attributes={
                "constraint_type": "CHECK_CONSTRAINT",
                "definition": "([display_name]<>'')",
            },
        )
    ]

    builder = CreateTable.from_metadata(
        "accounts",
        columns,
        constraints=constraints,
        schema="dbo",
        dialect="tsql",
    )
    sql = builder.build().sql

    assert "CREATE TABLE [dbo].[accounts]" in sql
    assert "[id] INTEGER NOT NULL IDENTITY(1, 1)" in sql
    assert "[display_name] NVARCHAR(100) NOT NULL DEFAULT 'unknown'" in sql
    assert "[payload] NVARCHAR(MAX)" in sql
    assert "[event_time] DATETIME2(3) NOT NULL" in sql
    assert "CONSTRAINT [pk_accounts] PRIMARY KEY ([id])" in sql
    assert "CONSTRAINT [chk_display_name] CHECK ([display_name] <> '')" in sql


def test_create_index_from_metadata_skips_primary_and_builds_secondary_indexes() -> None:
    """Test CreateIndex.from_metadata skips primary/auto indexes and builds unique, partial, covering indexes."""
    pk_index = {
        "index_name": "pk_users",
        "table_name": "users",
        "columns": ["id"],
        "is_primary": True,
        "is_unique": True,
    }
    sqlite_auto = {
        "index_name": "sqlite_autoindex_users_1",
        "table_name": "users",
        "columns": ["email"],
        "is_primary": False,
        "is_unique": True,
    }
    assert CreateIndex.from_metadata(pk_index, dialect="postgres") is None
    assert CreateIndex.from_metadata(sqlite_auto, dialect="sqlite") is None

    covering_partial = {
        "schema_name": "public",
        "table_name": "users",
        "index_name": "idx_users_email_active",
        "columns": "email ASC, tenant_id DESC",
        "included_columns": "display_name, created_at",
        "is_unique": True,
        "is_primary": False,
        "filter_definition": "is_active = TRUE",
    }
    idx_builder = CreateIndex.from_metadata(covering_partial, dialect="postgres")
    assert idx_builder is not None
    idx_sql = idx_builder.build().sql
    assert (
        'CREATE UNIQUE INDEX "idx_users_email_active" ON "public"."users"'
        '("email" ASC, "tenant_id" DESC) INCLUDE ("display_name", "created_at")'
    ) in idx_sql
    assert 'WHERE\n  "is_active" = TRUE' in idx_sql or 'WHERE "is_active" = TRUE' in idx_sql

    details = IndexDetails(
        ObjectIdentity(name="idx_posts_tags", object_type="index", schema="public", dialect="postgres"),
        attributes={
            "table_name": "posts",
            "columns": ["tags"],
            "access_method": "gin",
            "is_unique": False,
            "is_primary": False,
        },
    )
    gin_builder = CreateIndex.from_metadata(details, dialect="postgres")
    assert gin_builder is not None
    assert gin_builder.build().sql == 'CREATE INDEX "idx_posts_tags" ON "public"."posts" USING gin("tags")'


@pytest.mark.parametrize(
    ("dialect", "expected_table_fragment", "expected_index_fragment"),
    [
        (
            "postgres",
            'CREATE TABLE "app"."invoices"',
            'CREATE UNIQUE INDEX "idx_invoices_code" ON "app"."invoices"("code") INCLUDE ("total")',
        ),
        (
            "tsql",
            "CREATE TABLE [app].[invoices]",
            "CREATE UNIQUE INDEX [idx_invoices_code] ON [app].[invoices]([code]) INCLUDE ([total])",
        ),
        (
            "duckdb",
            'CREATE TABLE "app"."invoices"',
            'CREATE UNIQUE INDEX "idx_invoices_code" ON "app"."invoices"("code") INCLUDE ("total")',
        ),
        (
            "sqlite",
            'CREATE TABLE "app"."invoices"',
            'CREATE UNIQUE INDEX "idx_invoices_code" ON "app"."invoices"("code") INCLUDE ("total")',
        ),
        (
            "db2",
            "CREATE TABLE app.invoices",
            "CREATE UNIQUE INDEX idx_invoices_code ON app.invoices(code) INCLUDE (total)",
        ),
    ],
)
def test_compile_table_ddl_results_cross_dialect(
    dialect: str, expected_table_fragment: str, expected_index_fragment: str
) -> None:
    """Test compile_table_ddl_results renders table, index, and comment DDL across dialects from one payload."""
    columns = [
        {
            "column_name": "id",
            "data_type": "BIGINT",
            "is_nullable": "NO",
            "is_primary": True,
            "ordinal_position": 1,
            "comment": "Primary invoice identifier",
        },
        {
            "column_name": "code",
            "data_type": "VARCHAR",
            "max_length": 40,
            "is_nullable": "NO",
            "ordinal_position": 2,
        },
        {
            "column_name": "total",
            "data_type": "DECIMAL",
            "numeric_precision": 10,
            "numeric_scale": 2,
            "is_nullable": "NO",
            "column_default": "0",
            "ordinal_position": 3,
        },
    ]
    indexes = [
        {
            "index_name": "pk_invoices",
            "table_name": "invoices",
            "columns": ["id"],
            "is_primary": True,
            "is_unique": True,
        },
        {
            "index_name": "idx_invoices_code",
            "table_name": "invoices",
            "columns": ["code"],
            "included_columns": ["total"],
            "is_primary": False,
            "is_unique": True,
        },
    ]

    result = compile_table_ddl_results(
        "invoices",
        columns,
        schema="app",
        indexes=indexes,
        table_comment="Customer invoices",
        column_comments={"code": "External invoice code"},
        dialect=dialect,
    )

    assert isinstance(result, DDLResult)
    assert result.status == MetadataSupport.SUPPORTED
    assert result.fidelity == MetadataFidelity.GENERATED
    assert result.source == MetadataSource.GENERATED
    assert result.identity.name == "invoices"
    assert result.identity.schema == "app"
    assert result.ddl is not None
    assert expected_table_fragment in result.ddl
    assert expected_index_fragment in result.ddl
    assert "pk_invoices" not in result.ddl
    assert "COMMENT ON TABLE" in result.ddl
    assert "Customer invoices" in result.ddl
    assert "Primary invoice identifier" in result.ddl
    assert "External invoice code" in result.ddl
    assert result.ddl.endswith(";")


def test_compile_table_ddl_results_empty_columns_returns_unsupported() -> None:
    """Test compile_table_ddl_results returns an unsupported DDLResult when columns are empty."""
    result = compile_table_ddl_results("missing_table", [], schema="public", dialect="postgres")

    assert result.status == MetadataSupport.UNSUPPORTED
    assert result.fidelity == MetadataFidelity.UNSUPPORTED
    assert result.source == MetadataSource.GENERATED
    assert result.ddl is None
    assert result.identity.name == "missing_table"
    assert result.identity.schema == "public"
    assert result.warnings == ("No catalog columns found for public.missing_table",)


def test_compile_table_ddl_results_composite_fk_rows_and_per_column_index_rows() -> None:
    """Test multi-row composite ForeignKeyMetadata and per-column Db2 index rows."""
    columns = [
        {"column_name": "tenant_id", "data_type": "INTEGER", "is_nullable": 0, "is_primary": 1, "ordinal_position": 1},
        {"column_name": "order_id", "data_type": "INTEGER", "is_nullable": 0, "is_primary": 1, "ordinal_position": 2},
        {"column_name": "sku", "data_type": "VARCHAR", "max_length": 64, "is_nullable": 0, "ordinal_position": 3},
        {
            "column_name": "slug",
            "data_type": "VARCHAR",
            "max_length": 64,
            "is_nullable": 1,
            "generated_kind": "s",
            "column_default": "lower(sku)",
            "ordinal_position": 4,
        },
    ]
    foreign_keys = [
        ForeignKeyMetadata(
            table_name="order_items",
            column_name="tenant_id",
            referenced_table="orders",
            referenced_column="tenant_id",
            constraint_name="fk_order_items_orders",
        ),
        ForeignKeyMetadata(
            table_name="order_items",
            column_name="order_id",
            referenced_table="orders",
            referenced_column="id",
            constraint_name="fk_order_items_orders",
        ),
    ]
    indexes = [
        {
            "index_name": "idx_order_items_tenant_sku",
            "table_name": "order_items",
            "column_name": "sku",
            "column_position": 2,
            "is_unique": 0,
            "is_primary": 0,
        },
        {
            "index_name": "idx_order_items_tenant_sku",
            "table_name": "order_items",
            "column_name": "tenant_id",
            "column_position": 1,
            "is_unique": 0,
            "is_primary": 0,
        },
    ]

    result = compile_table_ddl_results(
        "order_items",
        columns,
        foreign_keys=foreign_keys,
        indexes=indexes,
        dialect="postgres",
    )

    assert result.ddl is not None
    assert 'PRIMARY KEY ("tenant_id", "order_id")' in result.ddl
    assert (
        'CONSTRAINT "fk_order_items_orders" FOREIGN KEY ("tenant_id", "order_id") '
        'REFERENCES "orders"("tenant_id", "id")'
    ) in result.ddl
    assert '"slug" VARCHAR(64) GENERATED ALWAYS AS (LOWER("sku")) STORED' in result.ddl
    assert 'CREATE INDEX "idx_order_items_tenant_sku" ON "order_items"("tenant_id", "sku")' in result.ddl

