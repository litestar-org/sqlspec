def _execute_script(connection: Any, ddl: str) -> None:
    """Execute every statement of a generated DDL script on a DB-API connection."""
    for statement in ddl.split(";\n\n"):
        text = statement.strip().rstrip(";")
        if text:
            connection.execute(text)


