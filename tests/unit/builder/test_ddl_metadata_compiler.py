    with DuckDBConfig(connection_config={"database": str(tmp_path / "replay.duckdb")}).provide_session() as replay:
        _replay(replay, _ddl_items(duck))
        replay.execute_script('INSERT INTO t ("Amount", "Email") VALUES (3, \'A@X\')')
