"""Unit tests for DDL builder computed columns, covering indexes, and sequence builders."""

import pytest
import sqlglot
from sqlglot import exp

from sqlspec import sql
from sqlspec.builder import ColumnDefinition, CreateIndex, CreateSequence, CreateTable, DropSequence
from sqlspec.builder._ddl import build_column_expression
from sqlspec.exceptions import SQLBuilderError


@pytest.mark.parametrize(
    ("identity", "generated", "expected_clause"),
    [
        (True, None, "GENERATED ALWAYS AS IDENTITY"),
        ("ALWAYS", None, "GENERATED ALWAYS AS IDENTITY"),
        ("ALWAYS AS IDENTITY", None, "GENERATED ALWAYS AS IDENTITY"),
        ("BY DEFAULT", None, "GENERATED BY DEFAULT AS IDENTITY"),
        ("BY DEFAULT AS IDENTITY", None, "GENERATED BY DEFAULT AS IDENTITY"),
        (None, True, "GENERATED ALWAYS AS IDENTITY"),
        (None, "ALWAYS", "GENERATED ALWAYS AS IDENTITY"),
        (None, "ALWAYS AS IDENTITY", "GENERATED ALWAYS AS IDENTITY"),
        (None, "BY DEFAULT", "GENERATED BY DEFAULT AS IDENTITY"),
        (None, "BY DEFAULT AS IDENTITY", "GENERATED BY DEFAULT AS IDENTITY"),
    ],
)
def test_column_definition_identity_variants(
    identity: str | bool | None, generated: str | bool | None, expected_clause: str
) -> None:
    """Verify identity column definitions emit GENERATED ALWAYS/BY DEFAULT AS IDENTITY."""
    col = ColumnDefinition("id", "BIGINT", identity=identity, generated=generated)
    expr = col.to_sqlglot(dialect="postgres")
    rendered = expr.sql(dialect="postgres")
    assert expected_clause in rendered
    assert build_column_expression(col, dialect="postgres").sql(dialect="postgres") == rendered


def test_column_definition_computed_expression_persisted_and_virtual() -> None:
    """Verify computed columns emit ComputedColumnConstraint for stored and virtual modes."""
    stored_col = ColumnDefinition("total", "NUMERIC(10,2)", generated_expression="price * quantity", persisted=True)
    stored_pg = stored_col.to_sqlglot(dialect="postgres").sql(dialect="postgres")
    stored_mysql = stored_col.to_sqlglot(dialect="mysql").sql(dialect="mysql")
    assert "GENERATED ALWAYS AS (price * quantity) STORED" in stored_pg
    assert "GENERATED ALWAYS AS (price * quantity) STORED" in stored_mysql

    virtual_col = ColumnDefinition("total", "NUMERIC(10,2)", generated_expression="price * quantity", persisted=False)
    virtual_mysql = virtual_col.to_sqlglot(dialect="mysql").sql(dialect="mysql")
    virtual_sqlite = virtual_col.to_sqlglot(dialect="sqlite").sql(dialect="sqlite")
    assert "GENERATED ALWAYS AS (price * quantity) VIRTUAL" in virtual_mysql
    assert "AS (price * quantity)" in virtual_sqlite
    assert "STORED" not in virtual_sqlite


def test_column_definition_computed_accepts_sqlglot_expr_and_legacy_generated_str() -> None:
    """Verify computed columns accept exp.Expr or an expression string in generated."""
    parsed_mul = sqlglot.parse_one("price * quantity")
    expr_col = ColumnDefinition("total", "NUMERIC(10,2)", generated_expression=parsed_mul, persisted=True)
    assert "GENERATED ALWAYS AS (price * quantity) STORED" in expr_col.to_sqlglot(dialect="postgres").sql(
        dialect="postgres"
    )

    legacy_col = ColumnDefinition("total", "NUMERIC(10,2)", generated="price * quantity", persisted=False)
    assert "GENERATED ALWAYS AS (price * quantity) VIRTUAL" in legacy_col.to_sqlglot(dialect="mysql").sql(
        dialect="mysql"
    )


def test_create_table_column_supports_identity_and_computed_columns() -> None:
    """Verify CreateTable.column forwards identity, generated_expression, and persisted options."""
    built = (
        CreateTable("line_items", dialect="postgres")
        .column("id", "BIGINT", primary_key=True, identity="BY DEFAULT")
        .column("price", "NUMERIC(10,2)", not_null=True)
        .column("quantity", "INT", not_null=True)
        .column("total", "NUMERIC(10,2)", generated_expression="price * quantity", persisted=True)
        .build()
    )
    assert "GENERATED BY DEFAULT AS IDENTITY" in built.sql
    assert 'GENERATED ALWAYS AS ("price" * "quantity") STORED' in built.sql


@pytest.mark.parametrize("dialect", ["postgres", "tsql", "duckdb", "sqlite"])
def test_create_index_covering_include_and_ordered_columns(dialect: str) -> None:
    """Verify CreateIndex renders ordered keys and INCLUDE covering columns across dialects."""
    built = (
        CreateIndex("idx_users_email")
        .on("users")
        .columns("email ASC", "created_at DESC")
        .include("name", "status")
        .build(dialect=dialect)
    )
    assert "ASC" in built.sql
    assert "DESC" in built.sql
    assert "INCLUDE (" in built.sql
    assert "name" in built.sql
    assert "status" in built.sql


def test_create_index_expression_keys_nulls_ordering_and_init_include() -> None:
    """Verify CreateIndex supports expression keys, NULLS FIRST/LAST, and init include argument."""
    built = (
        CreateIndex("idx_users_lookup", dialect="postgres", include=["status"])
        .on_table("users")
        .columns("LOWER(email)", "created_at DESC NULLS LAST", exp.Ordered(this=exp.column("score"), desc=True))
        .include(exp.to_identifier("name"))
        .build()
    )
    assert 'LOWER("email")' in built.sql
    assert '"created_at" DESC NULLS LAST' in built.sql
    assert '"score" DESC' in built.sql
    assert 'INCLUDE ("status", "name")' in built.sql


@pytest.mark.parametrize("dialect", ["postgres", "duckdb", "oracle"])
def test_create_sequence_and_drop_sequence_across_dialects(dialect: str) -> None:
    """Verify CreateSequence and DropSequence compile across Postgres, DuckDB, and Oracle."""
    create_sql = (
        CreateSequence(
            "users_id_seq",
            schema="public",
            if_not_exists=True,
            start_with=1,
            increment_by=1,
            min_value=1,
            max_value=10000,
            cycle=True,
            cache=20,
            dialect=dialect,
        )
        .build()
        .sql
    )
    assert "CREATE SEQUENCE" in create_sql
    assert "users_id_seq" in create_sql
    assert "START WITH 1" in create_sql
    assert "INCREMENT BY 1" in create_sql
    assert "MINVALUE 1" in create_sql
    assert "MAXVALUE 10000" in create_sql
    assert "CACHE 20" in create_sql
    assert "CYCLE" in create_sql

    drop_sql = DropSequence("users_id_seq", schema="public", if_exists=True, dialect=dialect).build().sql
    assert "DROP SEQUENCE IF EXISTS" in drop_sql
    assert "users_id_seq" in drop_sql
    assert "CASCADE" not in drop_sql


def test_sequence_builders_fluent_api_and_sql_factory() -> None:
    """Verify fluent methods on CreateSequence and DropSequence and SQLFactory entrypoints."""
    create_stmt = (
        sql
        .create_sequence("orders_seq", dialect="postgres")
        .in_schema("app")
        .if_not_exists()
        .start_with(10)
        .increment_by(5)
        .min_value(10)
        .max_value(5000)
        .cache(50)
        .cycle()
        .no_cycle()
        .build()
    )
    assert create_stmt.sql == (
        'CREATE SEQUENCE IF NOT EXISTS "app"."orders_seq" '
        "START WITH 10 INCREMENT BY 5 MINVALUE 10 MAXVALUE 5000 CACHE 50"
    )

    drop_stmt = sql.drop_sequence("orders_seq", dialect="postgres").in_schema("app").if_exists().cascade().build()
    assert drop_stmt.sql == 'DROP SEQUENCE IF EXISTS "app"."orders_seq" CASCADE'

    with pytest.raises(SQLBuilderError):
        CreateSequence("").build()

    with pytest.raises(SQLBuilderError):
        DropSequence("").build()
