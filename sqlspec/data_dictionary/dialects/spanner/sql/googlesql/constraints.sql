-- name: by_schema
-- dialect: spanner
SELECT
    tc.CONSTRAINT_CATALOG AS constraint_catalog,
    tc.CONSTRAINT_SCHEMA AS constraint_schema,
    tc.CONSTRAINT_NAME AS constraint_name,
    tc.TABLE_NAME AS table_name,
    tc.CONSTRAINT_TYPE AS constraint_type,
    kcu.COLUMN_NAME AS column_name,
    kcu.ORDINAL_POSITION AS ordinal_position,
    rc.UNIQUE_CONSTRAINT_NAME AS unique_constraint_name,
    rc.MATCH_OPTION AS match_option,
    rc.UPDATE_RULE AS update_rule,
    rc.DELETE_RULE AS delete_rule,
    cc.CHECK_CLAUSE AS check_clause
FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS AS tc
LEFT JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE AS kcu
  ON tc.CONSTRAINT_CATALOG = kcu.CONSTRAINT_CATALOG
  AND tc.CONSTRAINT_SCHEMA = kcu.CONSTRAINT_SCHEMA
  AND tc.CONSTRAINT_NAME = kcu.CONSTRAINT_NAME
LEFT JOIN INFORMATION_SCHEMA.REFERENTIAL_CONSTRAINTS AS rc
  ON tc.CONSTRAINT_CATALOG = rc.CONSTRAINT_CATALOG
  AND tc.CONSTRAINT_SCHEMA = rc.CONSTRAINT_SCHEMA
  AND tc.CONSTRAINT_NAME = rc.CONSTRAINT_NAME
LEFT JOIN INFORMATION_SCHEMA.CHECK_CONSTRAINTS AS cc
  ON tc.CONSTRAINT_CATALOG = cc.CONSTRAINT_CATALOG
  AND tc.CONSTRAINT_SCHEMA = cc.CONSTRAINT_SCHEMA
  AND tc.CONSTRAINT_NAME = cc.CONSTRAINT_NAME
WHERE (CAST(:schema_name AS STRING) IS NULL OR tc.CONSTRAINT_SCHEMA = :schema_name)
  AND (CAST(:table_name AS STRING) IS NULL OR tc.TABLE_NAME = :table_name)
ORDER BY tc.TABLE_NAME, tc.CONSTRAINT_NAME, kcu.ORDINAL_POSITION;

